  investor_id NOT LIKE "%© PitchBook Data, Inc.%"
  AND hq_global_region NOT IN ("Africa", "Asia", "Oceania")
  AND investor_status NOT IN (
    "Acquired/Merged",
    "Acquired/Merged (Operating Subsidiary)",
    "Fully Invested, No Longer Seeking New Investments",
    "Not Making New Investments",
    "Out of Business"
  )
  AND primary_investor_type NOT IN (
    "Asset Manager",
    "Business Development Company",
    "Corporate Development",
    "Corporate Venture Capital",
    "Corporation",
    "Family Office",
    "Fund of Funds",
    "Fundless Sponsor",
    "Government",
    "Growth/Expansion",
    "Hedge Fund",
    "Holding Company",
    "Impact Investing",
    "Infrastructure",
    "Investment Bank",
    "Lender/Debt Provider",
    "Limited Partner",
    "Merchant Banking Firm",
    "Mezzanine",
    "Mutual Fund",
    "Not-For-Profit Venture Capital",
    "Other",
    "Other Private Equity",
    "PE-Backed Company",
    "PE/Buyout",
    "Real Estate",
    "Secondary Buyer",
    "Special Purpose Acquisition Company (SPAC)",
    "Sovereign Wealth Fund",
    "University",
    "VC-Backed Company"
  )
