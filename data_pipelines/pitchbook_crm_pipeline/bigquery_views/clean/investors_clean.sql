-- View: Pitchbook.clean.investors_clean
-- Casts all numeric/timestamp/boolean fields from raw STRING ingestion,
-- strips PitchBook copyright footer rows, filters to active/relevant
-- investors (excludes non-VC types, inactive statuses, non-target regions),
-- and deduplicates by investor_id keeping the most recent ingestion.

